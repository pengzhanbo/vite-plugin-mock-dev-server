/**
 * Create a mock compiler for testing
 *
 * 创建用于测试的模拟编译器
 *
 * 中间件只需要 mock 数据，不依赖编译器的事件能力
 * （`build: true` 生成的独立 mock server 也只提供 mock 数据），
 * 因此这里不提供 `on` / `emit`，以免再次掩盖此类缺陷。
 *
 * The middleware only needs the mock data and does not depend on the compiler's
 * event capability (the standalone mock server generated by `build: true` also
 * only provides mock data), so `on` / `emit` are intentionally omitted to avoid
 * masking such defects again.
 *
 * @param mockData - Mock data to return / 要返回的 Mock 数据
 * @returns Mock compiler instance / 模拟编译器实例
 */
function createMockCompiler(mockData: Record<string, MockOptions> = {}): Compiler {
  return { mockData } as unknown as Compiler
}

type Listener = (...args: any[]) => void

/**
 * Create a mock request object
 *
 * 创建模拟请求对象
 *
 * @param options - Request options / 请求配置项
 * @param options.url - Request URL / 请求 URL
 * @param options.method - HTTP method / HTTP 方法
 * @param options.headers - Request headers / 请求头
 * @returns Mock request object / 模拟请求对象
 */
function createMockRequest(
  options: {
    url?: string
    method?: string
    headers?: Record<string, string>
  } = {},
): Connect.IncomingMessage {
  const { url = '/api/users', method = 'GET', headers = {} } = options
  const listeners: Record<string, Listener[]> = {}
  return {
    url,
    method,
    headers,
    socket: { encrypted: false },
    connection: { encrypted: false },
    addListener(event: string, callback: Listener) {
      if (!listeners[event]) {
        listeners[event] = []
      }
      listeners[event].push(callback)
      return this
    },
    on(event: string, callback: Listener) {
      return (this as any).addListener(event, callback)
    },
    once(event: string, callback: Listener) {
      return (this as any).addListener(event, callback)
    },
    emit(event: string, ...args: any[]) {
      listeners[event]?.forEach((cb) => cb(...args))
      return true
    },
    removeListener() {
      return this
    },
    removeAllListeners() {
      return this
    },
  } as unknown as Connect.IncomingMessage
}

function createEagerMultipartRequest(options: {
  url: string
  method: string
  headers: Record<string, string>
  body: Buffer
}): Connect.IncomingMessage {
  const listeners: Record<string, Listener[]> = {}
  let drained = false
  let ended = false

  function emit(event: string, ...args: any[]) {
    listeners[event]?.forEach((cb) => cb(...args))
  }

  function drain() {
    if (drained) {
      return
    }

    drained = true
    emit('data', options.body)
    ended = true
    emit('end')
  }

  return {
    url: options.url,
    method: options.method,
    headers: options.headers,
    socket: { encrypted: false },
    connection: { encrypted: false },
    addListener(event: string, callback: Listener) {
      if (!listeners[event]) {
        listeners[event] = []
      }
      listeners[event].push(callback)

      if (event === 'data') {
        drain()
      } else if (event === 'end' && ended) {
        callback()
      }

      return this
    },
    on(event: string, callback: Listener) {
      return (this as any).addListener(event, callback)
    },
    once(event: string, callback: Listener) {
      return (this as any).addListener(event, callback)
    },
    emit(event: string, ...args: any[]) {
      emit(event, ...args)
      return true
    },
    pause() {
      return this
    },
    resume() {
      return this
    },
    removeListener() {
      return this
    },
    removeAllListeners() {
      return this
    },
  } as unknown as Connect.IncomingMessage
}

/**
 * Create a mock response object
 *
 * 创建模拟响应对象
 *
 * @returns Mock response object / 模拟响应对象
 */
function createMockResponse(): any {
  const res: any = {
    statusCode: 0,
    statusMessage: '',
    headers: {} as Record<string, string | string[]>,
    cookies: {} as Record<string, any>,
    ended: false,
    data: null as any,
    setHeader(key: string, value: string | string[]) {
      this.headers[key] = value
    },
    getHeader(key: string) {
      return this.headers[key]
    },
    setCookie(key: string, value: string, options?: any) {
      this.cookies[key] = { value, options }
    },
    end(data?: any) {
      this.ended = true
      this.data = data
    },
  }
  return res
}

